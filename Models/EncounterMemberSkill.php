namespace Models;

/**
 * Skill usage of an encounter member.
 *
 * @package Models
 * @license OMS License 2.0
 * @link    https://jingga.app
 * @since   1.0.0
 */
class EncounterMemberSkill
{
    public int $id = 0;

    public int $member = 0;

    public Skill $skill;

    public int $casts = 0;

    public int $possible = 0;

    public int $amount = 0;

    /**
     * Constructor.
     *
     * @param int $id Model id
     *
     * @since 1.0.0
     */
    public function __construct(int $id = 0)
    {
        $this->id = $id;
        $this->skill = new NullSkill();
    }
}
