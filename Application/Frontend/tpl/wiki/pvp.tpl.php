<h1>PvP</h1>
<p>Player versus player combat is available in the open world and in many dedicated game modes. Arena and
battleground modes normalize your equipment so that skill matters more than gear.</p>
<table>
    <thead><tr><th>Mode</th><th>Description</th></tr></thead>
    <tbody>
        <tr><td>Arena</td><td>Small team fights (1v1, 2v2, 3v3).</td></tr>
        <tr><td>Capture the Flag</td><td>Steal the enemy flag and bring it home.</td></tr>
        <tr><td>Team Deathmatch</td><td>The team with the most kills wins.</td></tr>
        <tr><td>Capture the Objective(s)</td><td>Control points on the map to score.</td></tr>
        <tr><td>Escort</td><td>Escort or stop a moving objective.</td></tr>
        <tr><td>Siege</td><td>Attack or defend a fortress.</td></tr>
        <tr><td>MOBA</td><td>Push lanes and destroy the enemy base.</td></tr>
        <tr><td>Battle Royale</td><td>Last player standing.</td></tr>
        <tr><td>World vs. World</td><td>Servers fight for control over a huge map.</td></tr>
        <tr><td>Guild vs. Guild</td><td>Guilds fight for territory.</td></tr>
        <tr><td>Pet Battles</td><td>Turn based <a href="/pet/battle">pet duels</a>.</td></tr>
    </tbody>
</table>
