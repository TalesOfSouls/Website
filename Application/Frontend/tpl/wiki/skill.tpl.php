<h1>Skills</h1>
<p>Skills are the abilities your character uses in combat and beyond. Every class has its own skill tree and
specializations unlock additional branches. Skills scale with your primary attributes and can be modified by
equipment, enchantments and passive nodes.</p>
<h2>Skill types</h2>
<ul>
    <li><strong>Active skills</strong> - abilities you place on your action bar</li>
    <li><strong>Passive skills</strong> - permanent bonuses unlocked in the skill tree</li>
    <li><strong>Modifiers</strong> - change how an active skill behaves (range, area, damage type, ...)</li>
    <li><strong>Ultimate skills</strong> - powerful abilities with long cooldowns, unique per specialization</li>
</ul>
<h2>Damage types</h2>
<p>Skills deal physical (piercing, slashing, bludgeoning, stabbing), elemental (fire, water, wind, earth,
lightning, ice, poison) or magical (arcane, corrupted, holy) damage. Every damage type is countered by its own
defense value.</p>
