<h1>Mini Games</h1>
<p>Not everything is about fighting. The world offers many mini games for a quieter evening.</p>
<ul>
    <li><strong>Fishing</strong> - catch rare fish in every region</li>
    <li><strong>Jumping puzzles</strong> - reach hidden places with skill and patience</li>
    <li><strong>Mount races</strong> - compete for the fastest time</li>
    <li><strong>Holdouts</strong> - survive endless waves of enemies</li>
    <li><strong>Dodging</strong> - avoid everything that is thrown at you</li>
    <li><strong>Sailing</strong> - explore the seas with your own boat</li>
    <li><strong>Card &amp; board games</strong> - play against NPCs and players in taverns</li>
</ul>
<p>Many mini games have their own <a href="/ladder">ladder</a>.</p>
