<h1>Locations</h1>
<p>The world is divided into continents, regions and zones. Every region has its own climate, inhabitants,
reputation and resources.</p>
<h2>Types of locations</h2>
<ul>
    <li><strong>Cities</strong> - trade hubs with auction houses, banks and trainers</li>
    <li><strong>Villages</strong> - small settlements with quests and merchants</li>
    <li><strong>Wilderness</strong> - open areas for hunting and gathering</li>
    <li><strong>Dungeons &amp; raids</strong> - instanced challenges</li>
    <li><strong>Points of interest</strong> - hidden places that count towards discovery achievements</li>
</ul>
<p>See the <a href="/map">world map</a> for an overview.</p>
