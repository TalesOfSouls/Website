<h1>Leaderboards</h1>
<p>The leaderboards (ladder) rank players, characters and guilds across many categories. They can be filtered by
season, server, mode and class.</p>
<h2>Categories</h2>
<ul>
    <li>Level and speedruns</li>
    <li>Achievements and discoveries</li>
    <li>Raids, dungeons, trials, holdouts and jumping puzzles</li>
    <li>PvP modes: arena, capture the flag, siege, world vs. world and more</li>
    <li>Stats such as DPS, healing and health</li>
</ul>
<p>See the current standings on the <a href="/ladder">ladder</a>.</p>
