<h1>Story</h1>
<p>Long before the first kingdoms rose, the world was bound together by the souls of the dead. Every soul
that passed on left a fragment of itself behind - memories, skills, regrets - woven into the land itself.</p>
<p>When the Styx, a cursed river that devours souls, broke its banks, the balance shattered. Whole peoples
were changed: elves turned to blood, dwarves to ash and the dead began to walk again. The surviving
kingdoms are now divided between those who want to seal the Styx and those who hope to use its power.</p>
<p>You are one of the few who can hear the fragments of the departed. Their tales will guide you - and
sometimes mislead you.</p>
<p><em>The full story is told through the story quests. This page avoids major spoilers.</em></p>
