<h1>Guilds</h1>
<p>Guilds are communities of players. They share a guild bank, a guild hall and can claim territory in
Guild vs. Guild battles.</p>
<h2>Roles</h2>
<ul>
    <li><strong>Founder</strong> - full control over the guild</li>
    <li><strong>Moderator</strong> - can invite, promote and manage members</li>
    <li><strong>Member</strong> - regular guild members</li>
</ul>
<p>Guilds can additionally create custom ranks with individual permissions and define their focus
(PvE, PvP, raids, dungeons, World vs. World) to make recruiting easier.</p>
<p>Browse all guilds in the <a href="/guild/profile">guild list</a>.</p>
