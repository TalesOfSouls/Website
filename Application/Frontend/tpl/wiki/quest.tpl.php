<h1>Quests</h1>
<p>Quests guide you through the world and its stories. Many of them are small mysteries that can be solved in
more than one way - the outcome depends on what you investigate, whom you trust and which choices you make.</p>
<h2>Quest types</h2>
<ul>
    <li><strong>Story quests</strong> - the main storyline, chapter by chapter</li>
    <li><strong>Side quests</strong> - local stories, often with multiple endings</li>
    <li><strong>Class quests</strong> - unlock specializations and class specific rewards</li>
    <li><strong>Daily &amp; weekly quests</strong> - repeatable tasks for reputation and currency</li>
    <li><strong>Event quests</strong> - only available during world events</li>
</ul>
