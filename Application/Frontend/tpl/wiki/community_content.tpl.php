<h1>Community Content</h1>
<p>Tales of Souls is meant to be shaped by its players. Besides guides and builds, the community can create
content that becomes part of the game.</p>
<ul>
    <li><strong>Builds</strong> - share your builds in the <a href="/build/list">build list</a></li>
    <li><strong>Guides</strong> - leveling guides for every class and game mode</li>
    <li><strong>Tournaments</strong> - organize your own competitions</li>
    <li><strong>Housing &amp; towns</strong> - design houses and towns other players can visit</li>
    <li><strong>Feedback</strong> - suggest features on the <a href="/feedback">feedback board</a></li>
</ul>
<p>Content that becomes part of the game requires accepting the <a href="/cla">contributor license agreement</a>.</p>
