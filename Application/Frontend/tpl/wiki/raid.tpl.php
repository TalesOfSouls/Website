<h1>Raids</h1>
<p>Raids are the ultimate group challenge: large instanced encounters for 10 to 25 players with multiple
bosses, complex mechanics and the best loot in the game.</p>
<h2>Raid structure</h2>
<ul>
    <li>Every raid consists of several wings with 2 - 4 bosses each</li>
    <li>Loot is distributed individually - no loot drama</li>
    <li>A weekly lockout limits how often you can receive loot</li>
    <li>The first guilds to clear a raid are immortalized in the <a href="/ladder">raid ladder</a></li>
</ul>
<h2>Boss ranks</h2>
<p>Enemies are ranked as Regular, Elite, Champion, Boss, Final Boss, World Boss and Singularity. Raids
feature the Boss and Final Boss ranks.</p>
<p>Watch the best raid runs in the <a href="/recordings">recordings</a>.</p>
