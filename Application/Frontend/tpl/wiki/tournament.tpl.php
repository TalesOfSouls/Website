<h1>Tournaments</h1>
<p>Tournaments are organized competitions with brackets, schedules and rewards. They are hosted by us or by
the community and cover PvP, pet battles, speedruns and more.</p>
<h2>Formats</h2>
<ul>
    <li><strong>Single elimination</strong> - lose once and you are out</li>
    <li><strong>Double elimination</strong> - a second chance through the lower bracket</li>
    <li><strong>Round robin</strong> - everybody plays against everybody in a group</li>
    <li><strong>Swiss</strong> - players with similar records face each other</li>
</ul>
<p>Tournament matches are recorded and can be watched in the <a href="/recordings">recordings</a>.</p>
