<h1>Monsters</h1>
<p>The world is populated by animals, monsters and other creatures. Some are peaceful, some only defend
themselves and some hunt everything that moves.</p>
<h2>Categories</h2>
<ul>
    <li><strong>Monsters</strong> - hostile creatures found in the wild and in dungeons</li>
    <li><strong>Animals</strong> - wildlife that can be hunted for meat, leather and other materials</li>
    <li><strong>Fish</strong> - caught with the Fishing proficiency</li>
    <li><strong>Pets</strong> - creatures that can be tamed and raised</li>
    <li><strong>Farm animals</strong> - cows, chickens, pigs and more for your town</li>
</ul>
