<h1>Auction House</h1>
<p>The auction house is the central market of Tales of Souls. Players can sell tradable items to other
players on the same server.</p>
<h2>How it works</h2>
<ul>
    <li>Set a minimum bid and an optional instant buyout price</li>
    <li>Choose an auction duration</li>
    <li>A small deposit is charged when listing; it is returned when the item sells</li>
    <li>Sold items and gold are delivered by mail</li>
</ul>
<p>Only items of tradable item types and rarities can be listed. Check current offers on the
<a href="/auction">auction house page</a>.</p>
