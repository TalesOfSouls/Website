<h1>Towns</h1>
<p>Players can found and manage their own towns. Towns grow over time and attract NPC residents that offer
services, produce goods and protect the town.</p>
<h2>Features</h2>
<ul>
    <li>Build and upgrade houses, workshops, farms and defenses</li>
    <li>Attract residents with jobs and housing</li>
    <li>Raise farm animals and grow crops</li>
    <li>Rent houses to other players</li>
    <li>Host events and markets</li>
</ul>
<p>Manage your town in the <a href="/profile/town">town management</a>.</p>
