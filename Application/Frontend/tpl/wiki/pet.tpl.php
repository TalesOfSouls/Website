<h1>Pets</h1>
<p>Many creatures can be tamed and raised as pets. Pets accompany you in the world, help in combat and
compete in <a href="/pet/battle">pet battles</a>.</p>
<h2>Raising pets</h2>
<ul>
    <li><strong>Taming</strong> - wild creatures can be tamed with the Taming proficiency</li>
    <li><strong>Breeding</strong> - combine two pets to pass on their traits</li>
    <li><strong>Training</strong> - pets gain experience and learn new abilities</li>
    <li><strong>Day care</strong> - leave your pets in the <a href="/pet/daycare">day care</a> while you are offline</li>
</ul>
<p>Pets can additionally be equipped with pet equipment.</p>
