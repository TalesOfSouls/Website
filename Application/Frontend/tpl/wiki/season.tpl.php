<h1>Seasons</h1>
<p>Seasons are time limited leagues that start on fresh characters. Every season introduces new mechanics,
items or rules and has its own <a href="/ladder">ladder</a> and rewards.</p>
<h2>Modes</h2>
<table>
    <thead><tr><th>Mode</th><th>Description</th></tr></thead>
    <tbody>
        <tr><td>SC (Softcore)</td><td>Death is not permanent.</td></tr>
        <tr><td>HC (Hardcore)</td><td>Your character is gone when it dies.</td></tr>
        <tr><td>SF (Self found)</td><td>No trading - only use what you find or craft.</td></tr>
        <tr><td>S (Solo)</td><td>No grouping with other players.</td></tr>
        <tr><td>SSF (Solo self found)</td><td>Solo and self found combined.</td></tr>
        <tr><td>GF (Guild found)</td><td>Trading is only possible within your guild.</td></tr>
    </tbody>
</table>
<p>At the end of a season, characters are transferred to the permanent servers.</p>
